import { useState } from 'react';
import { Plus, Copy, Check, ExternalLink, Download, Trash2 } from 'lucide-react';
import { TARGET_COUNTRIES } from '../shared/countries';
import { CPA_OFFER_CATEGORIES } from '../shared/cpaCategories';
import type { Lead, Offer } from '../types';

interface OffersLeadsViewProps {
  offers: Offer[];
  leads: Lead[];
  onRefresh: () => void;
}

export function OffersLeadsView({ offers, leads, onRefresh }: OffersLeadsViewProps) {
  const [showCreateOffer, setShowCreateOffer] = useState(offers.length === 0);
  const [name, setName] = useState('');
  const [cpaCategory, setCpaCategory] = useState<string>(CPA_OFFER_CATEGORIES[0]);
  const [destinationUrl, setDestinationUrl] = useState('');
  const [slug, setSlug] = useState('');
  const [mode, setMode] = useState<'redirect' | 'lead_capture'>('redirect');
  const [headline, setHeadline] = useState('');
  const [subheadline, setSubheadline] = useState('');
  const [ctaLabel, setCtaLabel] = useState('Claim Offer Now');
  const [brandName, setBrandName] = useState('');
  const [benefitsInput, setBenefitsInput] = useState('Instant access after submitting\nDedicated country support\nVerified partner pricing');
  const [autoGenerateComments, setAutoGenerateComments] = useState(true);
  const [commentLanguage, setCommentLanguage] = useState('English');
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [copiedId, setCopiedId] = useState<string | null>(null);

  // Offers & Leads filters
  const [filterOfferCategory, setFilterOfferCategory] = useState('ALL');
  const [filterCountry, setFilterCountry] = useState('ALL');
  const [filterStage, setFilterStage] = useState('ALL');

  const handleCopy = async (id: string, value: string) => {
    await navigator.clipboard.writeText(value);
    setCopiedId(id);
    setTimeout(() => setCopiedId(null), 1500);
  };

  const handleCreateOffer = async (e: React.FormEvent) => {
    e.preventDefault();
    setSaving(true);
    setError(null);
    setNotice(null);
    try {
      const benefitPoints = benefitsInput
        .split(/\r?\n/)
        .map((s) => s.trim())
        .filter(Boolean);

      const res = await fetch('/api/offers', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          name: name.trim(),
          cpa_category: cpaCategory,
          slug: slug.trim() || undefined,
          mode,
          destination_url: destinationUrl.trim(),
          headline: headline.trim() || name.trim(),
          subheadline: subheadline.trim(),
          cta_label: ctaLabel.trim() || 'Claim Offer Now',
          brand_name: brandName.trim(),
          benefit_points: benefitPoints,
          auto_generate_comments: autoGenerateComments,
          comment_language: commentLanguage,
        }),
      });
      const data = (await res.json()) as {
        autoGeneratedCount?: number;
        autoGenerateError?: string;
        error?: string;
      };
      if (!res.ok) {
        setError(data.error || 'Could not create offer.');
      } else {
        setName('');
        setSlug('');
        setHeadline('');
        setSubheadline('');
        setDestinationUrl('');
        setShowCreateOffer(false);
        if (data.autoGeneratedCount && data.autoGeneratedCount > 0) {
          setNotice(`Offer published and ${data.autoGeneratedCount} tailored Reels comments were auto-created in Comment Studio.`);
        } else if (data.autoGenerateError) {
          setNotice(`Offer published. Note on auto-comments: ${data.autoGenerateError}`);
        }
        onRefresh();
      }
    } finally {
      setSaving(false);
    }
  };

  const handleDeleteOffer = async (id: string) => {
    const res = await fetch(`/api/offers/${id}`, { method: 'DELETE' });
    if (res.ok) onRefresh();
  };

  const handleStageChange = async (leadId: string, stage: Lead['stage']) => {
    await fetch(`/api/leads/${leadId}`, {
      method: 'PATCH',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ stage }),
    });
    onRefresh();
  };

  const handleDeleteLead = async (leadId: string) => {
    const res = await fetch(`/api/leads/${leadId}`, { method: 'DELETE' });
    if (res.ok) onRefresh();
  };

  const filteredOffers = offers.filter((offer) => {
    if (filterOfferCategory !== 'ALL' && offer.cpa_category !== filterOfferCategory) return false;
    return true;
  });

  const filteredLeads = leads.filter((l) => {
    if (filterCountry !== 'ALL' && l.country.toUpperCase() !== filterCountry) return false;
    if (filterStage !== 'ALL' && l.stage !== filterStage) return false;
    return true;
  });

  return (
    <div className="space-y-8">
      {/* Offers Header */}
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <h2 className="text-base font-semibold text-slate-900">Promotional Offers &amp; Tracking Links</h2>
          <p className="text-xs text-slate-500 mt-0.5">
            Add your CPA offer name, category, and offer link to generate tracked Reels comment URLs
          </p>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <select
            value={filterOfferCategory}
            onChange={(e) => setFilterOfferCategory(e.target.value)}
            className="px-3 py-2 text-xs bg-white border border-slate-300 rounded-lg text-slate-700"
          >
            <option value="ALL">All CPA Categories</option>
            {CPA_OFFER_CATEGORIES.map((cat) => (
              <option key={cat} value={cat}>
                {cat}
              </option>
            ))}
          </select>
          <button
            type="button"
            onClick={() => setShowCreateOffer((v) => !v)}
            className="inline-flex items-center gap-1.5 px-4 py-2 text-xs font-semibold text-white bg-[#1D4ED8] hover:bg-[#1E40AF] rounded-lg transition-colors whitespace-nowrap shrink-0"
          >
            <Plus className="w-3.5 h-3.5" />
            {showCreateOffer ? 'Close Offer Form' : 'Add CPA Offer'}
          </button>
        </div>
      </div>

      {notice && (
        <div className="px-4 py-3 bg-emerald-50/70 border border-emerald-200 rounded-lg text-xs text-emerald-900">
          {notice}
        </div>
      )}

      {showCreateOffer && (
        <form onSubmit={handleCreateOffer} className="bg-white border border-slate-200 rounded-lg p-6 space-y-4">
          {error && (
            <div className="px-4 py-2.5 bg-red-50 border border-red-200 rounded-lg text-xs text-red-900">
              {error}
            </div>
          )}

          {/* Core CPA Offer Fields */}
          <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">Offer Name</label>
              <input
                type="text"
                required
                value={name}
                onChange={(e) => setName(e.target.value)}
                placeholder="e.g. CashApp $750 Reward US"
                className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg"
              />
            </div>

            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">CPA Offer Category</label>
              <select
                value={cpaCategory}
                onChange={(e) => setCpaCategory(e.target.value)}
                className="w-full px-3 py-2 text-sm bg-white border border-slate-300 rounded-lg"
              >
                {CPA_OFFER_CATEGORIES.map((cat) => (
                  <option key={cat} value={cat}>
                    {cat}
                  </option>
                ))}
              </select>
            </div>

            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">
                {mode === 'redirect' ? 'Offer Link (CPA URL)' : 'Offer Link / Redirect URL (Optional)'}
              </label>
              <input
                type="url"
                required={mode === 'redirect'}
                value={destinationUrl}
                onChange={(e) => setDestinationUrl(e.target.value)}
                placeholder="https://cpa-network.com/click?offer=..."
                className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg"
              />
            </div>
          </div>

          <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">Offer Funnel Mode</label>
              <select
                value={mode}
                onChange={(e) => setMode(e.target.value as 'redirect' | 'lead_capture')}
                className="w-full px-3 py-2 text-sm bg-white border border-slate-300 rounded-lg"
              >
                <option value="redirect">Direct CPA Offer Link + Click Tracking (Recommended for CPA)</option>
                <option value="lead_capture">Hosted Lead Capture Page First (Optional)</option>
              </select>
            </div>
            <div>
              <label className="block text-xs font-medium text-slate-700 mb-1">Tracking Slug (/r/slug)</label>
              <input
                type="text"
                value={slug}
                onChange={(e) => setSlug(e.target.value)}
                placeholder="cashapp-750 (auto from Offer Name if blank)"
                className="w-full px-3 py-2 text-sm font-mono border border-slate-300 rounded-lg"
              />
            </div>
          </div>

          {mode === 'lead_capture' && (
            <div className="space-y-4 pt-2 border-t border-slate-100">
              <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
                <div className="md:col-span-2">
                  <label className="block text-xs font-medium text-slate-700 mb-1">Landing Page Headline</label>
                  <input
                    type="text"
                    value={headline}
                    onChange={(e) => setHeadline(e.target.value)}
                    placeholder="Claim Your Reward Offer Today"
                    className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg"
                  />
                </div>
                <div>
                  <label className="block text-xs font-medium text-slate-700 mb-1">Brand Name</label>
                  <input
                    type="text"
                    value={brandName}
                    onChange={(e) => setBrandName(e.target.value)}
                    placeholder="Acme Direct"
                    className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg"
                  />
                </div>
              </div>

              <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
                <div className="md:col-span-2">
                  <label className="block text-xs font-medium text-slate-700 mb-1">Subheadline / Value Proposition</label>
                  <input
                    type="text"
                    value={subheadline}
                    onChange={(e) => setSubheadline(e.target.value)}
                    placeholder="Enter your details below to unlock this limited regional offer."
                    className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg"
                  />
                </div>
                <div>
                  <label className="block text-xs font-medium text-slate-700 mb-1">Submit Button Text</label>
                  <input
                    type="text"
                    value={ctaLabel}
                    onChange={(e) => setCtaLabel(e.target.value)}
                    className="w-full px-3 py-2 text-sm border border-slate-300 rounded-lg"
                  />
                </div>
              </div>

              <div>
                <label className="block text-xs font-medium text-slate-700 mb-1">Key Offer Benefits (1 per line)</label>
                <textarea
                  rows={3}
                  value={benefitsInput}
                  onChange={(e) => setBenefitsInput(e.target.value)}
                  className="w-full px-3 py-2 text-xs border border-slate-300 rounded-lg"
                />
              </div>
            </div>
          )}

          <div className="flex flex-wrap items-center justify-between gap-4 pt-2 border-t border-slate-100">
            <div className="flex flex-wrap items-center gap-3">
              <label className="inline-flex items-center gap-2 text-xs text-slate-700 cursor-pointer">
                <input
                  type="checkbox"
                  checked={autoGenerateComments}
                  onChange={(e) => setAutoGenerateComments(e.target.checked)}
                  className="rounded border-slate-300 text-[#1D4ED8]"
                />
                <span>Auto-generate 15 Reels comments for this CPA offer</span>
              </label>
              {autoGenerateComments && (
                <select
                  value={commentLanguage}
                  onChange={(e) => setCommentLanguage(e.target.value)}
                  className="px-2.5 py-1 text-xs bg-white border border-slate-300 rounded-lg"
                >
                  <option value="English">English</option>
                  <option value="Bengali">Bengali</option>
                  <option value="Banglish">Banglish</option>
                  <option value="Multilingual">Multilingual</option>
                </select>
              )}
            </div>

            <div className="flex items-center gap-3">
              <button
                type="button"
                onClick={() => setShowCreateOffer(false)}
                className="px-4 py-2 text-xs font-medium text-slate-700 bg-white border border-slate-300 rounded-lg"
              >
                Cancel
              </button>
              <button
                type="submit"
                disabled={saving}
                className="px-5 py-2 text-xs font-semibold text-white bg-[#1D4ED8] hover:bg-[#1E40AF] rounded-lg"
              >
                {saving ? 'Saving...' : 'Save CPA Offer'}
              </button>
            </div>
          </div>
        </form>
      )}

      {/* Offers Table */}
      <section className="bg-white border border-slate-200 rounded-lg overflow-hidden">
        {filteredOffers.length === 0 ? (
          <div className="p-8 text-center">
            <p className="text-sm font-medium text-slate-900">
              {offers.length === 0 ? 'No CPA offers added yet' : 'No offers match this CPA category'}
            </p>
            <p className="mt-1 text-xs text-slate-500">
              {offers.length === 0
                ? 'Add your CPA Offer Name, Category, and Offer Link above to create a tracked URL (/r/your-offer) for Reels comments.'
                : 'Select another CPA category from the filter dropdown above.'}
            </p>
          </div>
        ) : (
          <div className="divide-y divide-slate-200">
            {filteredOffers.map((offer) => {
              const conv = offer.clicks > 0 ? ((offer.leads / offer.clicks) * 100).toFixed(1) : '0.0';
              return (
                <div key={offer.id} className="p-5 flex flex-col lg:flex-row lg:items-center justify-between gap-4">
                  <div className="space-y-1.5 min-w-0">
                    <div className="flex flex-wrap items-center gap-2">
                      <h3 className="text-sm font-semibold text-slate-900">{offer.name}</h3>
                      <span className="text-xs font-medium text-[#1D4ED8] bg-blue-50 border border-blue-200/80 px-2 py-0.5 rounded">
                        {offer.cpa_category || 'Other CPA Offer'}
                      </span>
                      <span className="text-xs text-slate-500">
                        · {offer.mode === 'lead_capture' ? 'Lead Capture Page' : 'Direct CPA Link'}
                      </span>
                    </div>
                    {offer.destination_url && (
                      <p className="text-xs text-slate-600 truncate">
                        Offer Link: <span className="font-mono text-slate-700">{offer.destination_url}</span>
                      </p>
                    )}
                    <div className="flex flex-wrap items-center gap-3 text-xs font-mono text-slate-500">
                      <span className="text-slate-800">{offer.tracking_url}</span>
                      <button
                        type="button"
                        onClick={() => handleCopy(`link-${offer.id}`, offer.tracking_url)}
                        className="inline-flex items-center gap-1 text-[#1D4ED8] hover:underline font-sans font-medium"
                      >
                        {copiedId === `link-${offer.id}` ? <Check className="w-3 h-3" /> : <Copy className="w-3 h-3" />}
                        {copiedId === `link-${offer.id}` ? 'Copied' : 'Copy Tracking Link'}
                      </button>
                      <button
                        type="button"
                        onClick={() => handleCopy(`wh-${offer.id}`, offer.webhook_url)}
                        className="inline-flex items-center gap-1 text-slate-600 hover:text-slate-900 font-sans"
                      >
                        {copiedId === `wh-${offer.id}` ? <Check className="w-3 h-3" /> : <Copy className="w-3 h-3" />}
                        {copiedId === `wh-${offer.id}` ? 'Webhook Copied' : 'Copy Postback / Webhook'}
                      </button>
                    </div>
                  </div>

                  <div className="flex items-center gap-6 shrink-0">
                    <div className="flex items-center gap-5 text-right font-mono tabular-nums">
                      <div>
                        <p className="text-xs text-slate-500 font-sans">Clicks</p>
                        <p className="text-sm font-semibold text-slate-900">{offer.clicks}</p>
                      </div>
                      <div>
                        <p className="text-xs text-slate-500 font-sans">Leads</p>
                        <p className="text-sm font-semibold text-slate-900">{offer.leads}</p>
                      </div>
                      <div>
                        <p className="text-xs text-slate-500 font-sans">Conv.</p>
                        <p className="text-sm font-semibold text-[#16A34A]">{conv}%</p>
                      </div>
                    </div>

                    <div className="flex items-center gap-2">
                      <a
                        href={`/r/${offer.slug}`}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-700 bg-slate-100 hover:bg-slate-200 rounded-lg whitespace-nowrap shrink-0"
                      >
                        <ExternalLink className="w-3.5 h-3.5" />
                        Test Link
                      </a>
                      <button
                        type="button"
                        onClick={() => handleDeleteOffer(offer.id)}
                        title="Delete offer"
                        className="p-1.5 text-slate-400 hover:text-[#DC2626]"
                      >
                        <Trash2 className="w-4 h-4" />
                      </button>
                    </div>
                  </div>
                </div>
              );
            })}
          </div>
        )}
      </section>

      {/* Captured Leads Inbox */}
      <section className="bg-white border border-slate-200 rounded-lg overflow-hidden">
        <div className="px-5 py-4 border-b border-slate-200 flex flex-wrap items-center justify-between gap-4">
          <div>
            <h2 className="text-sm font-semibold text-slate-900">Captured Leads ({filteredLeads.length})</h2>
            <p className="text-xs text-slate-500 mt-0.5">Real visitor submissions from your promoted offer links &amp; CPA postbacks</p>
          </div>

          <div className="flex flex-wrap items-center gap-2">
            <select
              value={filterCountry}
              onChange={(e) => setFilterCountry(e.target.value)}
              className="px-3 py-1.5 text-xs bg-white border border-slate-300 rounded-lg"
            >
              <option value="ALL">All Countries</option>
              {TARGET_COUNTRIES.map((c) => (
                <option key={c.code} value={c.code}>
                  {c.name} ({c.code})
                </option>
              ))}
            </select>
            <select
              value={filterStage}
              onChange={(e) => setFilterStage(e.target.value)}
              className="px-3 py-1.5 text-xs bg-white border border-slate-300 rounded-lg"
            >
              <option value="ALL">All Stages</option>
              <option value="new">New</option>
              <option value="contacted">Contacted</option>
              <option value="qualified">Qualified</option>
              <option value="converted">Converted</option>
            </select>
            <a
              href="/api/leads/export"
              className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-700 bg-slate-100 hover:bg-slate-200 rounded-lg whitespace-nowrap shrink-0"
            >
              <Download className="w-3.5 h-3.5" />
              Download CSV
            </a>
          </div>
        </div>

        {filteredLeads.length === 0 ? (
          <div className="p-10 text-center">
            <p className="text-sm font-medium text-slate-900">No leads captured yet</p>
            <p className="mt-1 text-xs text-slate-500">
              Open a Hosted Lead Capture offer or connect your CPA Postback/Webhook URL to receive live conversions here.
            </p>
          </div>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-left border-collapse">
              <thead>
                <tr className="border-b border-slate-200 text-xs text-slate-500 bg-slate-50/70">
                  <th className="py-2.5 px-5 font-medium">Lead Contact</th>
                  <th className="py-2.5 px-4 font-medium">Country</th>
                  <th className="py-2.5 px-4 font-medium">Source</th>
                  <th className="py-2.5 px-4 font-medium">Offer</th>
                  <th className="py-2.5 px-4 font-medium">Stage</th>
                  <th className="py-2.5 px-5 font-medium text-right">Captured</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100 text-sm">
                {filteredLeads.map((lead) => (
                  <tr key={lead.id} className="hover:bg-slate-50/70">
                    <td className="py-3 px-5">
                      <div className="font-medium text-slate-900">{lead.full_name}</div>
                      <div className="text-xs text-slate-500">
                        {lead.email}
                        {lead.phone ? ` · ${lead.phone}` : ''}
                      </div>
                    </td>
                    <td className="py-3 px-4 font-mono text-xs text-slate-700">{lead.country}</td>
                    <td className="py-3 px-4 capitalize text-xs text-slate-600">{lead.source_platform}</td>
                    <td className="py-3 px-4 text-xs text-slate-700">{lead.offer_name || 'Offer'}</td>
                    <td className="py-3 px-4">
                      <select
                        value={lead.stage}
                        onChange={(e) => handleStageChange(lead.id, e.target.value as Lead['stage'])}
                        className="px-2 py-1 text-xs bg-white border border-slate-300 rounded text-slate-800"
                      >
                        <option value="new">New</option>
                        <option value="contacted">Contacted</option>
                        <option value="qualified">Qualified</option>
                        <option value="converted">Converted</option>
                      </select>
                    </td>
                    <td className="py-3 px-5 text-right">
                      <div className="flex items-center justify-end gap-3">
                        <span className="text-xs font-mono tabular-nums text-slate-500">
                          {new Date(lead.created_at).toLocaleDateString()}
                        </span>
                        <button
                          type="button"
                          onClick={() => handleDeleteLead(lead.id)}
                          title="Delete lead"
                          className="text-slate-400 hover:text-[#DC2626]"
                        >
                          <Trash2 className="w-3.5 h-3.5" />
                        </button>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </section>
    </div>
  );
}
